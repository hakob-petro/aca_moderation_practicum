"""HTTP, authentication and failure handling; students edit policy.py."""
import asyncio
from contextlib import asynccontextmanager
import hmac
import json
import logging
import math
import os
import time
import uuid
from typing import Literal

from fastapi import Depends, FastAPI, Header, HTTPException, Request
from openai import APIConnectionError, APIStatusError, APITimeoutError, AsyncOpenAI
from pydantic import BaseModel, ConfigDict, Field, field_validator

from model_client import read_score, score_request
from policy import decide

logger = logging.getLogger("uvicorn.error")
KEY = os.environ["GATEWAY_KEY"]
MODEL_KEY = os.environ["MODEL_KEY"]
if min(len(KEY), len(MODEL_KEY)) < 24:
    raise ValueError("Use the random keys generated by ./prepare")
TIMEOUT = float(os.environ.get("MODEL_TIMEOUT", "15"))
LOW = float(os.environ.get("APPROVE_BELOW", "0.3"))
HIGH = float(os.environ.get("REMOVE_AT", "0.8"))
if not (0 <= LOW < HIGH <= 1 and math.isfinite(TIMEOUT) and 0 < TIMEOUT <= 120):
    raise ValueError("Need 0 <= APPROVE_BELOW < REMOVE_AT <= 1 and 0 < MODEL_TIMEOUT <= 120")
MODEL = os.environ.get("MODEL_NAME", "moderator")


@asynccontextmanager
async def lifespan(app):
    async with AsyncOpenAI(base_url=os.environ["MODEL_URL"], api_key=MODEL_KEY,
                           max_retries=0, timeout=TIMEOUT) as client:
        app.state.client = client
        yield


app = FastAPI(title="My moderation gateway", lifespan=lifespan)


@app.middleware("http")
async def request_log(request: Request, call_next):
    request.state.id = uuid.uuid4().hex
    start, status = time.perf_counter(), 500
    try:
        response = await call_next(request)
        status = response.status_code
        response.headers["X-Request-ID"] = request.state.id
        return response
    finally:
        # No keys, request bodies, comments, or upstream response bodies.
        logger.info(json.dumps({"event": "request", "request_id": request.state.id,
            "path": request.url.path, "status": status,
            "ms": round((time.perf_counter() - start) * 1000, 1),
            "decision": getattr(request.state, "decision", None)}))


def authorize(authorization: str = Header(default="")):
    if not hmac.compare_digest(authorization.encode(), f"Bearer {KEY}".encode()):
        raise HTTPException(401, "Valid gateway Bearer key required")


class Comment(BaseModel):
    model_config = ConfigDict(extra="forbid")
    comment: str = Field(min_length=1, max_length=2000)
    rule: Literal["advertising", "legal"]

    @field_validator("comment")
    @classmethod
    def not_blank(cls, value):
        if not value.strip():
            raise ValueError("Comment cannot be blank")
        return value


@app.get("/healthz")
def health():
    # Liveness only: do not wake a GPU for Docker's five-second health check.
    return {"status": "ok", "check": "gateway only"}


@app.post("/moderate", dependencies=[Depends(authorize)])
async def moderate(body: Comment, request: Request):
    try:
        # Wall-clock deadline includes connection, queues and response; no automatic retries.
        result = await asyncio.wait_for(request.app.state.client.chat.completions.create(
            **score_request(body.rule, body.comment, MODEL)), timeout=TIMEOUT)
        score, p_yes = read_score(result)
    except (TimeoutError, APITimeoutError):
        raise HTTPException(504, "Model timed out; no moderation decision was made") from None
    except (APIConnectionError, APIStatusError):
        raise HTTPException(503, "Model unavailable; no moderation decision was made") from None
    except (ValueError, KeyError, TypeError, IndexError, AttributeError):
        raise HTTPException(502, "Invalid model response; no moderation decision was made") from None
    decision = decide(p_yes, LOW, HIGH)
    request.state.decision = decision
    return {"request_id": request.state.id, "rule": body.rule, "model": MODEL,
            "score": score, "p_yes": p_yes, "decision": decision,
            "thresholds": {"approve_below": LOW, "remove_at": HIGH}}
